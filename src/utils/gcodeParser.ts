export interface GCodeParseResult {
  printHours: number;
  printMinutes: number;
  modelWeight: number; // in grams
  rawTimeSeconds?: number;
  slicerDetected?: string;
  success: boolean;
  message?: string;
}

export function parseGCodeContent(content: string): GCodeParseResult {
  const lines = content.split(/\r?\n/);
  // Scan both the first 250 lines (Cura headers) and the last 600 lines (Prusa/Orca/Bambu footers)
  const headLines = lines.slice(0, 250);
  const tailLines = lines.slice(-600);
  const targetLines = [...headLines, ...tailLines];

  let detectedSeconds: number | null = null;
  let detectedGrams: number | null = null;
  let detectedSlicer: string | undefined = undefined;

  // Patterns for Print Time:
  // 1) PrusaSlicer/Orca: ; estimated printing time (normal mode) = 3h 25m 12s  or  35m 20s or 1d 2h 3m
  // 2) Cura: ;TIME:1161 (in seconds)
  // 3) General: ; print_time = ...
  const prusaTimeRegex =
    /;\s*(?:estimated printing time(?:\s*\([^)]*\))?|print_time)\s*=\s*(.*)/i;
  const curaTimeRegex = /;\s*TIME\s*:\s*(\d+)/i;

  // Patterns for Filament Weight:
  // 1) Prusa/Orca: ; total filament used [g] = 14.52  or  ; filament used [g] = 14.52, 4.25
  // 2) Cura: ;Filament used: 0.836139m (if weight is not present, calculate via 1.75mm PLA default ~2.98g/m)
  // 3) Bambu/Orca: ; filament_used_g = 14.52
  const totalWeightRegex =
    /;\s*(?:total filament used \[g\]|filament used \[g\]|total filament weight \[g\])\s*=\s*([0-9.,\s]+)/i;
  const curaMeterRegex = /;\s*Filament used\s*:\s*([0-9.]+)\s*m/i;

  for (const line of targetLines) {
    // Slicer detection
    if (/generated by PrusaSlicer/i.test(line)) detectedSlicer = 'PrusaSlicer';
    else if (/generated by BambuStudio/i.test(line)) detectedSlicer = 'Bambu Studio';
    else if (/generated by OrcaSlicer/i.test(line)) detectedSlicer = 'OrcaSlicer';
    else if (/generated by Cura/i.test(line) || /;FLAVOR:/i.test(line))
      detectedSlicer = detectedSlicer || 'Cura';

    // Time parsing - Prusa/Orca formatted string
    if (detectedSeconds === null) {
      const pMatch = line.match(prusaTimeRegex);
      if (pMatch && pMatch[1]) {
        const timeStr = pMatch[1].trim();
        const days = (timeStr.match(/(\d+)\s*d/i) || [])[1];
        const hours = (timeStr.match(/(\d+)\s*h/i) || [])[1];
        const mins = (timeStr.match(/(\d+)\s*m(?:in)?/i) || [])[1];
        const secs = (timeStr.match(/(\d+)\s*s(?:ec)?/i) || [])[1];

        if (days || hours || mins || secs) {
          const totalSecs =
            (days ? parseInt(days, 10) * 86400 : 0) +
            (hours ? parseInt(hours, 10) * 3600 : 0) +
            (mins ? parseInt(mins, 10) * 60 : 0) +
            (secs ? parseInt(secs, 10) : 0);
          if (totalSecs > 0) detectedSeconds = totalSecs;
        }
      }
    }

    // Time parsing - Cura seconds format
    if (detectedSeconds === null) {
      const cMatch = line.match(curaTimeRegex);
      if (cMatch && cMatch[1]) {
        detectedSeconds = parseInt(cMatch[1], 10);
      }
    }

    // Weight parsing - direct gram representation (supports multi-material sum)
    const wMatch = line.match(totalWeightRegex);
    if (wMatch && wMatch[1]) {
      const parts = wMatch[1].split(',').map((p) => parseFloat(p.trim()));
      const sum = parts.reduce((acc, val) => acc + (Number.isFinite(val) ? val : 0), 0);
      if (sum > 0) {
        detectedGrams = sum;
      }
    }

    // Weight fallback - Cura meters to grams (standard 1.75mm PLA ~1.24 g/cm3 => ~2.98g per meter)
    if (detectedGrams === null) {
      const mMatch = line.match(curaMeterRegex);
      if (mMatch && mMatch[1]) {
        const meters = parseFloat(mMatch[1]);
        if (Number.isFinite(meters) && meters > 0) {
          // Volume = pi * (0.175/2)^2 * (meters * 100) = 2.405 cm3 per meter
          // Weight = 2.405 * 1.24 g/cm3 ~ 2.98 g/m
          detectedGrams = Math.round(meters * 2.98 * 10) / 10;
        }
      }
    }
  }

  const success = detectedSeconds !== null || detectedGrams !== null;
  const printHours = detectedSeconds ? Math.floor(detectedSeconds / 3600) : 0;
  const printMinutes = detectedSeconds
    ? Math.round((detectedSeconds % 3600) / 60)
    : 0;

  return {
    printHours,
    printMinutes,
    modelWeight: detectedGrams ? Math.round(detectedGrams * 10) / 10 : 0,
    rawTimeSeconds: detectedSeconds ?? undefined,
    slicerDetected: detectedSlicer,
    success,
    message: success
      ? `Detected ${detectedSlicer || 'Slicer'} metadata: ${printHours}h ${printMinutes}m, ${detectedGrams ? `${detectedGrams.toFixed(1)}g` : 'weight not found'}`
      : 'Could not find time or weight metadata in the uploaded G-code file.',
  };
}
