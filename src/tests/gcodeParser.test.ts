import { describe, expect, it } from 'vitest';
import {
  calculateWeightedMaterialCost,
  extractFilamentSlotsFromGCode,
  extractFilamentSlotsFromXml,
  parseGCodeContent,
} from '../utils/gcodeParser';

describe('G-Code & Sliced File Parser (Bambu Studio & OrcaSlicer)', () => {
  it('extracts multi-color filament slots from Bambu Studio XML slice_info.config', () => {
    const sampleXml = `<?xml version="1.0" encoding="UTF-8"?>
    <config>
      <plate>
        <filament id="1" type="PETG" color="#18181B" used_m="10.5" used_g="31.5" />
        <filament id="2" type="PETG" color="#7DD3FC" used_m="5.2" used_g="15.6" />
        <filament id="3" type="PLA" color="#F4F4F5" used_m="2.1" used_g="6.3" />
      </plate>
    </config>`;

    const slots = extractFilamentSlotsFromXml(sampleXml);
    expect(slots).toHaveLength(3);
    expect(slots[0]).toEqual({
      id: 1,
      type: 'PETG',
      color: '#18181B',
      usedGrams: 31.5,
    });
    expect(slots[1]).toEqual({
      id: 2,
      type: 'PETG',
      color: '#7DD3FC',
      usedGrams: 15.6,
    });
    expect(slots[2]).toEqual({
      id: 3,
      type: 'PLA',
      color: '#F4F4F5',
      usedGrams: 6.3,
    });
  });

  it('aggregates multi-color filament usage across multiple plates in XML', () => {
    const multiPlateXml = `<?xml version="1.0" encoding="UTF-8"?>
    <config>
      <plate id="1">
        <filament id="1" type="PETG" color="#18181B" used_g="10.0" />
        <filament id="2" type="PETG" color="#F4F4F5" used_g="20.0" />
      </plate>
      <plate id="2">
        <filament id="1" type="PETG" color="#18181B" used_g="15.5" />
        <filament id="2" type="PETG" color="#F4F4F5" used_g="5.0" />
      </plate>
    </config>`;

    const slots = extractFilamentSlotsFromXml(multiPlateXml);
    expect(slots).toHaveLength(2);
    expect(slots[0].usedGrams).toBe(25.5);
    expect(slots[1].usedGrams).toBe(25.0);
  });

  it('extracts multi-color filament slots from Bambu/Orca G-Code comments', () => {
    const sampleGCode = `; generated by BambuStudio 01.09.02
; filament used [g] = 25.4, 18.2, 7.6
; filament_colour = #18181B;#F4F4F5;#7DD3FC
; filament_type = PETG;PETG;PLA
; estimated printing time (normal mode) = 2h 45m 12s
`;

    const slots = extractFilamentSlotsFromGCode(sampleGCode);
    expect(slots).toHaveLength(3);
    expect(slots[0]).toEqual({
      id: 1,
      type: 'PETG',
      color: '#18181B',
      usedGrams: 25.4,
    });
    expect(slots[1]).toEqual({
      id: 2,
      type: 'PETG',
      color: '#F4F4F5',
      usedGrams: 18.2,
    });
    expect(slots[2]).toEqual({
      id: 3,
      type: 'PLA',
      color: '#7DD3FC',
      usedGrams: 7.6,
    });
  });

  it('parses print duration and filament weight correctly from standard G-Code', () => {
    const gcode = `; estimated printing time (normal mode) = 3h 15m 00s
; total filament used [g] = 84.5
; filament_type = PETG
`;
    const stats = parseGCodeContent(gcode);
    expect(stats.success).toBe(true);
    expect(stats.printHours).toBe(3);
    expect(stats.printMinutes).toBe(15);
    expect(stats.modelWeight).toBe(84.5);
  });

  it('calculates weighted material cost across multiple slots accurately', () => {
    const slots = [
      {
        slotId: 1,
        type: 'PETG',
        color: '#18181B',
        usedGrams: 100,
        customSpoolPrice: 10.0,
        customSpoolWeight: 1000, // 0.01 / g -> 1.00
      },
      {
        slotId: 2,
        type: 'PETG',
        color: '#F4F4F5',
        usedGrams: 50,
        customSpoolPrice: 20.0,
        customSpoolWeight: 1000, // 0.02 / g -> 1.00
      },
    ];

    const cost = calculateWeightedMaterialCost(slots, 10.0, 1000);
    expect(cost).toBeCloseTo(2.0, 4);
  });
});
